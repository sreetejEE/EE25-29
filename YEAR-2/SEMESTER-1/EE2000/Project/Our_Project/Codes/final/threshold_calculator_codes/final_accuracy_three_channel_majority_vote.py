# 11. FINAL TEST
# ============================================================

def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    print("=" * 72)
    print("FINAL THREE-CHANNEL FAULT CLASSIFICATION TEST")
    print("=" * 72)
    print("Test columns:", TEST_COLUMNS)
    print("Channels:", CHANNELS)
    print("Decision: at least 2 of 3 channels must agree.")

    # Load thresholds frozen during the separate calibration stage.
    thresholds = load_decision_thresholds()

    # Load the Gaussian median/sigma calibration for all classes/channels.
    calibrations = load_all_feature_calibrations()

    print("\nFrozen thresholds:")
    for channel in CHANNELS:
        t = thresholds[str(channel)]
        print(
            f"CH{channel}: MIN_SCORE={float(t['min_score']):.6f}, "
            f"MIN_MARGIN={float(t['min_margin']):.6f}"
        )

    # Cache recordings for each class/channel.
    recording_data = {}
    for class_name, class_info in CLASS_FILES.items():
        for channel in CHANNELS:
            path = get_data_path(class_info, channel)
            recording_data[(class_name, channel)] = load_test_recordings(path)

    final_rows = []
    channel_rows = []
    feature_rows = []
    band_rows = []

    # Iterate by true class and test recording column. Each column is
    # evaluated across all three channels before majority voting.
    for true_class in CLASS_NAMES:
        print(f"\nFinal testing: {true_class}")

        for column_number in TEST_COLUMNS:
            channel_predictions = {}
            per_channel_results = {}

            for channel in CHANNELS:
                signal = recording_data[(true_class, channel)][column_number]
                features = extract_features(signal)

                result = classify_one_channel(
                    features,
                    calibrations[channel],
                    thresholds[str(channel)],
                )

                channel_predictions[channel] = result["prediction"]
                per_channel_results[channel] = result

                channel_row = {
                    "True_Class": true_class,
                    "CSV_Column": column_number,
                    "Channel": channel,
                    "Predicted_Class": result["prediction"],
                    "Best_Matching_Class": result["best_class"],
                    "Best_Score": result["best_score"],
                    "Second_Best_Class": result["second_class"],
                    "Second_Score": result["second_score"],
                    "Score_Margin": result["margin"],
                    "MIN_SCORE": float(thresholds[str(channel)]["min_score"]),
                    "MIN_MARGIN": float(thresholds[str(channel)]["min_margin"]),
                    "Correct": int(result["prediction"] == true_class),
                }

                for class_name in CLASS_NAMES:
                    channel_row[f"Score_{class_name}"] = (
                        result["class_scores"][class_name]
                    )

                channel_rows.append(channel_row)

                feature_rows.append({
                    "True_Class": true_class,
                    "CSV_Column": column_number,
                    "Channel": channel,
                    **features,
                })

                for detail in result["band_details"]:
                    band_rows.append({
                        "True_Class": true_class,
                        "CSV_Column": column_number,
                        "Channel": channel,
                        **detail,
                    })

            final_prediction = majority_vote(channel_predictions)

            final_row = {
                "True_Class": true_class,
                "CSV_Column": column_number,
                "CH1_Prediction": channel_predictions[1],
                "CH2_Prediction": channel_predictions[2],
                "CH3_Prediction": channel_predictions[3],
                "Final_Prediction": final_prediction,
                "Correct": int(final_prediction == true_class),
            }

            # Preserve individual channel scores/margins in the final
            # row as well, for easier inspection.
            for channel in CHANNELS:
                result = per_channel_results[channel]
                final_row[f"CH{channel}_Best_Class"] = result["best_class"]
                final_row[f"CH{channel}_Best_Score"] = result["best_score"]
                final_row[f"CH{channel}_Margin"] = result["margin"]

            final_rows.append(final_row)

            print(
                f"  Column {column_number}: "
                f"CH1={channel_predictions[1]}, "
                f"CH2={channel_predictions[2]}, "
                f"CH3={channel_predictions[3]} "
                f"=> FINAL={final_prediction}"
            )

    # ========================================================
    # 12. METRICS AND OUTPUT FILES
    # ========================================================

    final_df = pd.DataFrame(final_rows)
    channel_df = pd.DataFrame(channel_rows)
    features_df = pd.DataFrame(feature_rows)
    bands_df = pd.DataFrame(band_rows)

    if final_df.empty:
        raise RuntimeError("No final test recordings were processed.")

    total_recordings = len(final_df)
    final_accuracy = 100.0 * final_df["Correct"].mean()

    final_rejected = final_df["Final_Prediction"].eq("UNKNOWN")
    rejection_rate = 100.0 * final_rejected.mean()
    accepted_count = int((~final_rejected).sum())

    accepted_accuracy = (
        100.0 * final_df.loc[~final_rejected, "Correct"].mean()
        if accepted_count > 0 else 0.0
    )

    # Individual channel metrics, before majority voting.
    channel_metric_rows = []
    for channel in CHANNELS:
        subset = channel_df[channel_df["Channel"] == channel]
        channel_rejected = subset["Predicted_Class"].eq("UNKNOWN")
        channel_accepted = ~channel_rejected

        channel_metric_rows.append({
            "Channel": f"CH{channel}",
            "Total": len(subset),
            "Correct_Including_Unknown_As_Wrong": int(
                (subset["Predicted_Class"] == subset["True_Class"]).sum()
            ),
            "Accuracy_Percent": 100.0 * (
                subset["Predicted_Class"] == subset["True_Class"]
            ).mean(),
            "Accepted": int(channel_accepted.sum()),
            "Rejection_Rate_Percent": 100.0 * channel_rejected.mean(),
            "Accuracy_Among_Accepted_Percent": (
                100.0 * subset.loc[
                    channel_accepted, "Predicted_Class"
                ].eq(subset.loc[channel_accepted, "True_Class"]).mean()
                if channel_accepted.any() else 0.0
            ),
        })

    channel_metrics_df = pd.DataFrame(channel_metric_rows)

    per_class = final_df.groupby("True_Class").agg(
        Total=("Correct", "count"),
        Correct=("Correct", "sum"),
    )
    per_class["Accuracy_Percent"] = (
        100.0 * per_class["Correct"] / per_class["Total"]
    )

    cm = confusion_matrix(
        final_df["True_Class"],
        final_df["Final_Prediction"],
        labels=PREDICTION_LABELS,
    )

    confusion_df = pd.DataFrame(
        cm[:len(CLASS_NAMES), :],
        index=CLASS_NAMES,
        columns=PREDICTION_LABELS,
    )

    final_df.to_csv(OUTPUT_DIR / "final_three_channel_results.csv", index=False)
    channel_df.to_csv(OUTPUT_DIR / "final_individual_channel_results.csv", index=False)
    features_df.to_csv(OUTPUT_DIR / "final_three_channel_features.csv", index=False)
    bands_df.to_csv(OUTPUT_DIR / "final_three_channel_band_scores.csv", index=False)
    channel_metrics_df.to_csv(OUTPUT_DIR / "final_channel_metrics.csv", index=False)
    per_class.to_csv(OUTPUT_DIR / "final_three_channel_per_class_accuracy.csv")
    confusion_df.to_csv(OUTPUT_DIR / "final_three_channel_confusion_matrix.csv")

    # Machine-readable summary of the final test.
    summary = {
        "test_columns": TEST_COLUMNS,
        "channels": CHANNELS,
        "total_recordings": total_recordings,
        "majority_vote_exact_accuracy_percent": float(final_accuracy),
        "majority_vote_rejection_rate_percent": float(rejection_rate),
        "accepted_recordings": accepted_count,
        "accuracy_among_accepted_percent": float(accepted_accuracy),
        "decision_rule": "At least two channels must independently predict the same class.",
        "threshold_file": str(THRESHOLD_CONFIG_PATH),
    }

    with open(
        OUTPUT_DIR / "final_three_channel_metrics.json",
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(summary, file, indent=4)

    print("\n" + "=" * 72)
    print("FINAL THREE-CHANNEL TEST RESULTS")
    print("=" * 72)
    print(f"Total recordings                 : {total_recordings}")
    print(f"Majority-vote exact accuracy     : {final_accuracy:.2f}%")
    print(f"Final UNKNOWN/rejection rate     : {rejection_rate:.2f}%")
    print(f"Accepted recordings              : {accepted_count}")
    print(f"Accuracy among accepted          : {accepted_accuracy:.2f}%")

    print("\nINDIVIDUAL CHANNEL METRICS")
    print(channel_metrics_df.to_string(index=False))

    print("\nPER-CLASS MAJORITY-VOTE ACCURACY")
    print(per_class.to_string())

    print("\nMAJORITY-VOTE CONFUSION MATRIX")
    print(confusion_df.to_string())

    print("\nCLASSIFICATION REPORT")
    print(
        classification_report(
            final_df["True_Class"],
            final_df["Final_Prediction"],
            labels=PREDICTION_LABELS,
            zero_division=0,
        )
    )

    print("\nSaved outputs in:")
    print(OUTPUT_DIR)


if __name__ == "__main__":
    main()
