# 4. LOAD RAW CALIBRATION RECORDINGS
# ============================================================

def load_recordings(file_path):
    if not file_path.is_file():
        raise FileNotFoundError(f"Raw data file not found:\n{file_path}")

    # The uploaded classifier used header=None; preserve that assumption.
    df = pd.read_csv(file_path, header=None)

    recordings = {}

    for col_number in CALIBRATION_COLUMNS:
        col_index = col_number - 1

        if col_index >= df.shape[1]:
            raise ValueError(
                f"{file_path.name} has {df.shape[1]} columns, "
                f"but column {col_number} was requested."
            )

        signal = pd.to_numeric(
            df.iloc[:, col_index],
            errors="coerce",
        ).dropna().to_numpy(dtype=np.float64)

        if signal.size == 0 or not np.all(np.isfinite(signal)):
            raise ValueError(
                f"Empty or non-finite signal in {file_path.name}, "
                f"column {col_number}."
            )

        recordings[col_number] = signal

    return recordings


# ============================================================
# 5. EXTRACT 20 FFT FEATURES FROM ONE RECORDING
# ============================================================

def extract_features(signal):
    signal = np.asarray(signal, dtype=np.float64)
    signal = signal - np.mean(signal)

    resampled = resample_poly(
        signal,
        up=1,
        down=2,
        window=fir_coefficients,
    )

    required_samples = NUM_BLOCKS * FFT_SIZE
    if len(resampled) < required_samples:
        raise ValueError(
            f"Insufficient samples: got {len(resampled)}, "
            f"need {required_samples}."
        )

    resampled = resampled[:required_samples]
    blocks = resampled.reshape(NUM_BLOCKS, FFT_SIZE)

    fft_values = np.fft.rfft(
        blocks * hann_window,
        axis=1,
    )
    fft_magnitudes = np.abs(fft_values)

    features = {}

    for band_index, (low, high) in enumerate(BANDS):
        if band_index == len(BANDS) - 1:
            mask = (
                (fft_frequencies >= low)
                & (fft_frequencies <= high)
            )
        else:
            mask = (
                (fft_frequencies >= low)
                & (fft_frequencies < high)
            )

        if not np.any(mask):
            raise ValueError(f"No FFT bins in band {low}-{high} Hz.")

        band_magnitudes = fft_magnitudes[:, mask]
        band_frequencies = fft_frequencies[mask]

        peak_indices = np.argmax(band_magnitudes, axis=1)

        peak_magnitudes = band_magnitudes[
            np.arange(NUM_BLOCKS), peak_indices
        ]
        peak_frequencies = band_frequencies[peak_indices]

        features[FREQ_COLS[band_index]] = float(
            np.median(peak_frequencies)
        )
        features[MAG_COLS[band_index]] = float(
            np.median(peak_magnitudes)
        )

    return features


# ============================================================
# 6. LOAD GAUSSIAN FEATURE CALIBRATION
# ============================================================

def load_feature_calibration(file_path):
    if not file_path.is_file():
        raise FileNotFoundError(
            f"Feature calibration file not found:\n{file_path}"
        )

    df = pd.read_csv(file_path, index_col=0)

    required_rows = [
        "MEDIAN",
        "GAUSSIAN_SIGMA",
    ]

    for row_name in required_rows:
        if row_name not in df.index:
            raise ValueError(
                f"Missing row '{row_name}' in {file_path}. "
                f"Available rows: {df.index.tolist()}"
            )

    if df.shape[1] != 20:
        raise ValueError(
            f"Expected 20 feature columns in {file_path}; "
            f"found {df.shape[1]}."
        )

    median_values = df.loc["MEDIAN"].to_numpy(dtype=float)
    sigma_values = df.loc["GAUSSIAN_SIGMA"].to_numpy(dtype=float)

    calibration = {}

    for band_index in range(10):
        freq_position = 2 * band_index
        mag_position = 2 * band_index + 1

        freq_col = FREQ_COLS[band_index]
        mag_col = MAG_COLS[band_index]

        calibration[freq_col] = {
            "median": float(median_values[freq_position]),
            "sigma": float(sigma_values[freq_position]),
        }
        calibration[mag_col] = {
            "median": float(median_values[mag_position]),
            "sigma": float(sigma_values[mag_position]),
        }

    for feature_name, values in calibration.items():
        if not np.isfinite(values["median"]):
            raise ValueError(
                f"Non-finite median for {feature_name} in {file_path}"
            )
        if not np.isfinite(values["sigma"]) or values["sigma"] < 0:
            raise ValueError(
                f"Invalid Gaussian sigma for {feature_name} in {file_path}"
            )

    return calibration


def load_all_channel_calibrations():
    # Structure: calibrations[channel][class_name][feature_name]
    calibrations = {}

    for channel in CHANNELS:
        calibrations[channel] = {}

        for class_name, class_info in CLASS_FILES.items():
            path = get_feature_calibration_path(class_info, channel)
            calibrations[channel][class_name] = (
                load_feature_calibration(path)
            )

    return calibrations


# ============================================================
# 7. GAUSSIAN FEATURE SCORE
# ============================================================

def gaussian_feature_score(value, median, sigma):
    """
    Gaussian similarity kernel:
        exp(-(x-mu)^2 / (2*sigma^2))

    This is a similarity score, not a probability.

    If sigma is exactly zero:
        exact equality -> 1
        otherwise -> 0

    No arbitrary sigma floor is introduced.
    """
    if sigma == 0:
        return 1.0 if value == median else 0.0

    z = (value - median) / sigma
    return float(np.exp(-0.5 * z * z))


# ============================================================
# 8. SCORE ALL CLASSES FOR ONE CHANNEL
# ============================================================

def calculate_class_score(features, calibration):
    total_score = 0.0

    for band_index in range(10):
        freq_col = FREQ_COLS[band_index]
        mag_col = MAG_COLS[band_index]

        freq_cal = calibration[freq_col]
        mag_cal = calibration[mag_col]

        freq_score = gaussian_feature_score(
            features[freq_col],
            freq_cal["median"],
            freq_cal["sigma"],
        )
        mag_score = gaussian_feature_score(
            features[mag_col],
            mag_cal["median"],
            mag_cal["sigma"],
        )

        total_score += (freq_score + mag_score) / 2.0

    return float(total_score)


def score_one_channel(features, channel_calibrations):
    class_scores = {}

    for class_name, calibration in channel_calibrations.items():
        class_scores[class_name] = calculate_class_score(
            features,
            calibration,
        )

    ranked = sorted(
        class_scores.items(),
        key=lambda item: item[1],
        reverse=True,
    )

    best_class, best_score = ranked[0]
    second_class, second_score = ranked[1]

    return {
        "best_class": best_class,
        "best_score": float(best_score),
        "second_class": second_class,
        "second_score": float(second_score),
        "margin": float(best_score - second_score),
        "class_scores": class_scores,
    }


# ============================================================
# 9. COLLECT PER-CHANNEL THRESHOLD-CALIBRATION RESULTS
# ============================================================

def collect_channel_results(calibrations):
    rows = []

    for channel in CHANNELS:
        print(f"\nCollecting calibration results for CH{channel}")

        for true_class, class_info in CLASS_FILES.items():
            data_path = get_data_path(class_info, channel)
            recordings = load_recordings(data_path)

            for column_number, signal in recordings.items():
                features = extract_features(signal)

                result = score_one_channel(
                    features,
                    calibrations[channel],
                )

                row = {
                    "Channel": channel,
                    "True_Class": true_class,
                    "CSV_Column": column_number,
                    "Best_Matching_Class": result["best_class"],
                    "Best_Score": result["best_score"],
                    "Second_Score": result["second_score"],
                    "Score_Margin": result["margin"],
                }

                for class_name in CLASS_NAMES:
                    row[f"Score_{class_name}"] = (
                        result["class_scores"][class_name]
                    )

                rows.append(row)

                print(
                    f"  {true_class}, column {column_number}: "
                    f"best={result['best_class']}, "
                    f"score={result['best_score']:.4f}, "
                    f"margin={result['margin']:.4f}"
                )

    return pd.DataFrame(rows)


# ============================================================
# 10. SELECT MINIMUM SCORE AND MARGIN FOR ONE CHANNEL
# ============================================================

def select_channel_thresholds(channel_results):
    """
    Conservative channel-specific selection:
      1. Do not accept any incorrectly top-ranked calibration record.
      2. Maximize correctly accepted records.
      3. Tie-break using the higher score cutoff, then margin cutoff.

    If no safe useful pair exists, this channel is configured to
    reject every recording rather than being given unsafe thresholds.
    """

    scores = channel_results["Best_Score"].to_numpy(dtype=float)
    margins = channel_results["Score_Margin"].to_numpy(dtype=float)

    correct_top1 = (
        channel_results["Best_Matching_Class"].to_numpy()
        == channel_results["True_Class"].to_numpy()
    )

    score_candidates = np.unique(
        np.concatenate(([0.0], scores, [10.000001]))
    )
    margin_candidates = np.unique(
        np.concatenate(([0.0], margins, [10.000001]))
    )

    best = None

    for score_threshold in score_candidates:
        for margin_threshold in margin_candidates:
            accepted = (
                (scores >= score_threshold)
                & (margins >= margin_threshold)
            )

            wrong_accepted = int(np.sum(accepted & ~correct_top1))
            correct_accepted = int(np.sum(accepted & correct_top1))

            if wrong_accepted != 0:
                continue

            candidate_key = (
                correct_accepted,
                float(score_threshold),
                float(margin_threshold),
            )

            if best is None or candidate_key > best["key"]:
                best = {
                    "key": candidate_key,
                    "min_score": float(score_threshold),
                    "min_margin": float(margin_threshold),
                    "correctly_accepted": correct_accepted,
                    "wrongly_accepted": wrong_accepted,
                    "accepted": int(np.sum(accepted)),
                    "status": "CALIBRATED",
                }

    if best is None or best["correctly_accepted"] == 0:
        return {
            "min_score": 10.000001,
            "min_margin": 10.000001,
            "correctly_accepted": 0,
            "wrongly_accepted": 0,
            "accepted": 0,
            "status": "NO_SAFE_ACCEPTANCE_REJECT_ALL",
        }

    best.pop("key")
    return best


# ============================================================
# 11. APPLY EACH CHANNEL'S THRESHOLDS
# ============================================================

def apply_channel_threshold(result, threshold):
    accepted = (
        result["best_score"] >= threshold["min_score"]
        and result["margin"] >= threshold["min_margin"]
    )

    return result["best_class"] if accepted else "UNKNOWN"


def majority_vote(channel_predictions):
    """
    Accept a class only if at least two of the three channels
    independently predict that same class.
    Otherwise return UNKNOWN.
    """
    accepted_predictions = [
        prediction
        for prediction in channel_predictions.values()
        if prediction != "UNKNOWN"
    ]

    counts = {}
    for prediction in accepted_predictions:
        counts[prediction] = counts.get(prediction, 0) + 1

    winners = [
        class_name
        for class_name, count in counts.items()
        if count >= 2
    ]

    if len(winners) == 1:
        return winners[0]

    return "UNKNOWN"


