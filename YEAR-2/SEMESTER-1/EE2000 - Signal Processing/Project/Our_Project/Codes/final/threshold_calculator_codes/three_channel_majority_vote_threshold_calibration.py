def main():
    print("=" * 72)
    print("THREE-CHANNEL DECISION THRESHOLD CALIBRATION")
    print("=" * 72)
    print("Channels:", CHANNELS)
    print("Calibration columns:", CALIBRATION_COLUMNS)
    print("Rule: accept a fault only if at least 2 channels agree.")

    calibrations = load_all_channel_calibrations()
    all_results = collect_channel_results(calibrations)

    thresholds_by_channel = {}
    threshold_summary_rows = []

    # Select a separate min score and min margin for each channel.
    for channel in CHANNELS:
        channel_results = all_results[
            all_results["Channel"] == channel
        ].copy()

        selected = select_channel_thresholds(channel_results)
        thresholds_by_channel[str(channel)] = selected

        threshold_summary_rows.append({
            "Channel": channel,
            "MIN_SCORE": selected["min_score"],
            "MIN_MARGIN": selected["min_margin"],
            "Correctly_Accepted": selected["correctly_accepted"],
            "Wrongly_Accepted": selected["wrongly_accepted"],
            "Total_Accepted": selected["accepted"],
            "Status": selected["status"],
        })

    # Apply the independent channel thresholds to every calibration case,
    # then apply the 2-out-of-3 voting rule.
    lookup = {}
    for _, row in all_results.iterrows():
        channel = int(row["Channel"])
        key = (row["True_Class"], int(row["CSV_Column"]))

        lookup.setdefault(key, {})
        lookup[key][channel] = {
            "best_class": row["Best_Matching_Class"],
            "best_score": float(row["Best_Score"]),
            "margin": float(row["Score_Margin"]),
        }

    voting_rows = []

    for (true_class, column_number), channel_results in sorted(lookup.items()):
        channel_predictions = {}

        row = {
            "True_Class": true_class,
            "CSV_Column": column_number,
        }

        for channel in CHANNELS:
            result = channel_results[channel]
            prediction = apply_channel_threshold(
                result,
                thresholds_by_channel[str(channel)],
            )

            channel_predictions[channel] = prediction
            row[f"CH{channel}_Prediction"] = prediction
            row[f"CH{channel}_Best_Score"] = result["best_score"]
            row[f"CH{channel}_Margin"] = result["margin"]

        final_prediction = majority_vote(channel_predictions)
        row["Final_Majority_Vote"] = final_prediction
        row["Correct"] = final_prediction == true_class
        voting_rows.append(row)

    voting_results = pd.DataFrame(voting_rows)
    threshold_summary = pd.DataFrame(threshold_summary_rows)

    config = {
        "channels": CHANNELS,
        "calibration_columns": CALIBRATION_COLUMNS,
        "class_names": CLASS_NAMES,
        "scoring_method": "Gaussian similarity using median and GAUSSIAN_SIGMA",
        "channel_thresholds": thresholds_by_channel,
        "final_decision_rule": (
            "Accept a class only when at least two channels independently "
            "predict that same class; otherwise UNKNOWN."
        ),
    }

    config_path = OUTPUT_DIR / "three_channel_decision_thresholds.json"
    with open(config_path, "w", encoding="utf-8") as file:
        json.dump(config, file, indent=4)

    all_results.to_csv(
        OUTPUT_DIR / "per_channel_threshold_calibration_results.csv",
        index=False,
    )
    threshold_summary.to_csv(
        OUTPUT_DIR / "per_channel_threshold_summary.csv",
        index=False,
    )
    voting_results.to_csv(
        OUTPUT_DIR / "majority_vote_calibration_results.csv",
        index=False,
    )

    print("\n" + "=" * 72)
    print("PER-CHANNEL DECISION THRESHOLDS")
    print("=" * 72)
    print(threshold_summary.to_string(index=False))

    print("\n" + "=" * 72)
    print("MAJORITY-VOTING CALIBRATION RESULTS")
    print("=" * 72)
    print(voting_results.to_string(index=False))

    if len(voting_results):
        correct_count = int(voting_results["Correct"].sum())
        total_count = len(voting_results)
        print(
            f"\nMajority-vote calibration accuracy: "
            f"{correct_count}/{total_count} "
            f"({100.0 * correct_count / total_count:.2f}%)"
        )

    print("\nSaved files:")
    print(config_path)
    print(OUTPUT_DIR / "per_channel_threshold_calibration_results.csv")
    print(OUTPUT_DIR / "per_channel_threshold_summary.csv")
    print(OUTPUT_DIR / "majority_vote_calibration_results.csv")

    print(
        "\nNOTE: These are calibration-set results, not final test accuracy. "
        "Keep the separate final test recordings untouched."
    )


if __name__ == "__main__":
    main()
